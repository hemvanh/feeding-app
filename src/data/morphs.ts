function pack(names: string[]): string[] {
  const normal = 'Normal / Wild Type'
  const rest = [...new Set(names.filter((name) => name !== normal && name !== 'Hybrid'))].sort((a, b) =>
    a.localeCompare(b),
  )
  return [normal, ...rest]
}

